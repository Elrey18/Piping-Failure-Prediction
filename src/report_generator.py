from pathlib import Path
from datetime import datetime
from fpdf import FPDF


BASE_DIR = Path(__file__).resolve().parents[1]
REPORTS_DIR = BASE_DIR / "reports"
REPORTS_DIR.mkdir(exist_ok=True)


def get_recommendation(prediction):
    if prediction == "Normal":
        return [
            "Continue normal operation.",
            "Maintain routine inspection schedule.",
            "No immediate maintenance action required.",
            "Continue periodic monitoring."
        ]

    if prediction == "Moderate":
        return [
            "Increase inspection frequency.",
            "Monitor corrosion and material loss trends.",
            "Plan preventive maintenance.",
            "Review operating pressure and inspection records."
        ]

    return [
        "Immediate engineering inspection required.",
        "Assess damaged section for repair or replacement.",
        "Consider reducing operating pressure.",
        "Perform full pipeline integrity assessment."
    ]


def safe_text(value):
    """
    Convert text to PDF-safe plain text.
    Avoids unsupported characters and layout issues.
    """
    return str(value).replace("–", "-").replace("—", "-").replace("•", "-")


def write_section_title(pdf, title):
    pdf.ln(4)
    pdf.set_font("Helvetica", "B", 12)
    pdf.set_x(pdf.l_margin)
    pdf.cell(pdf.epw, 8, safe_text(title), new_x="LMARGIN", new_y="NEXT")


def write_line(pdf, text, height=7):
    pdf.set_font("Helvetica", "", 11)
    pdf.set_x(pdf.l_margin)
    pdf.multi_cell(
        pdf.epw,
        height,
        safe_text(text),
        new_x="LMARGIN",
        new_y="NEXT"
    )


def generate_pdf_report(last_prediction):
    """
    Generate a PDF inspection report from the latest prediction.

    Returns:
        pdf_bytes: bytes
        filename: str
    """

    prediction = last_prediction["prediction"]
    confidence = last_prediction["confidence"]
    probabilities = last_prediction["probabilities"]
    input_data = last_prediction["input_data"]

    timestamp = datetime.now().strftime("%Y-%m-%d %H:%M:%S")
    filename_time = datetime.now().strftime("%Y%m%d_%H%M%S")
    filename = f"pipeline_inspection_report_{filename_time}.pdf"

    pdf = FPDF()
    pdf.set_auto_page_break(auto=True, margin=15)
    pdf.set_margins(left=15, top=15, right=15)
    pdf.add_page()

    # Header
    pdf.set_font("Helvetica", "B", 18)
    pdf.cell(
        pdf.epw,
        10,
        "Pipeline Integrity AI",
        new_x="LMARGIN",
        new_y="NEXT",
        align="C"
    )

    pdf.set_font("Helvetica", "", 12)
    pdf.cell(
        pdf.epw,
        8,
        "Predictive Maintenance and Condition Assessment Report",
        new_x="LMARGIN",
        new_y="NEXT",
        align="C"
    )

    pdf.ln(6)

    # Report Information
    write_section_title(pdf, "Report Information")
    write_line(pdf, f"Generated On: {timestamp}")
    write_line(pdf, "Model Used: Random Forest Classifier")
    write_line(pdf, "Application: Pipeline Integrity AI")

    # Prediction Summary
    write_section_title(pdf, "Prediction Summary")
    write_line(pdf, f"Predicted Pipeline Condition: {prediction}")
    write_line(pdf, f"Model Confidence: {confidence:.2f}%")

    write_section_title(pdf, "Class Probabilities")

    for condition, probability in probabilities.items():
        write_line(pdf, f"{condition}: {probability:.2f}%")

    # Inspection Data
    write_section_title(pdf, "Inspection Input Data")

    inspection_labels = {
        "Pipe_Size_mm": "Pipe Size (mm)",
        "Thickness_mm": "Thickness (mm)",
        "Max_Pressure_psi": "Maximum Pressure (psi)",
        "Temperature_C": "Temperature (deg C)",
        "Corrosion_Impact_Percent": "Corrosion Impact (%)",
        "Thickness_Loss_mm": "Thickness Loss (mm)",
        "Material_Loss_Percent": "Material Loss (%)",
        "Time_Years": "Pipeline Age (Years)",
        "Material": "Material",
        "Grade": "Grade",
    }

    for key, label in inspection_labels.items():
        value = input_data.get(key, "N/A")
        write_line(pdf, f"{label}: {value}")

    # Recommendations
    write_section_title(pdf, "Engineering Recommendation")

    for rec in get_recommendation(prediction):
        write_line(pdf, f"- {rec}")

    # Disclaimer
    write_section_title(pdf, "Disclaimer")
    write_line(
        pdf,
        "This report is generated by a machine learning model for educational "
        "and decision-support purposes. It should not replace professional "
        "engineering judgment, field inspection, regulatory compliance checks, "
        "or certified pipeline integrity assessment.",
        height=6
    )

    pdf.ln(8)
    write_line(pdf, "Engineer/Inspector Signature: ______________________________")

    # Convert PDF to bytes
    pdf_bytes = bytes(pdf.output(dest="S"))

    # Save local copy
    report_path = REPORTS_DIR / filename
    with open(report_path, "wb") as file:
        file.write(pdf_bytes)

    return pdf_bytes, filename